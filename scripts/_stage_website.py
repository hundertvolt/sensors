#!/usr/bin/env python3
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Stages one device's website from html/ and js/: index.html with the stylesheet, the icon and the definitions
inlined, and js/main.js's import closure bundled into js/app.js, each module after the ones it imports. An import
outside the one-line form, a cycle or a missing module stops the build (SPECIFICATION.md H.2, H.7)."""

# Usage: scripts/_stage_website.py <definitions.json> <stage_dir>
# Reads html/ and js/ of this script's own tree; writes only <stage_dir>/index.html and <stage_dir>/js/app.js, creating
# <stage_dir> if absent (its caller wipes it). An error exits 1 naming the rule, the file and line, and the fix.

import argparse
import base64
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
_STYLESHEET_TAG = '<link rel="stylesheet" href="style.css">'
_ICON_TAG = '<link rel="icon" href="favicon.ico">'
_HEAD_END = "</head>"
_DEFINITIONS_OPEN = '<script type="application/json" id="inlined-definitions">'
_IMPORT_FORM = 'import { a, b } from "./x.js";'
_NAME = r"[A-Za-z_$][\w$]*"
_IMPORT_LINE = re.compile(rf'import \{{\s*{_NAME}(?:\s*,\s*{_NAME})*\s*,?\s*\}} from "\./(?P<file>[\w.-]+\.js)";')


class StageError(Exception):
    # One broken rule: where (file, or file:line), what is wrong, and the one fix.
    def __init__(self, where: str, what: str, fix: str) -> None:
        super().__init__(f"{where}: {what} - fix: {fix}")


def _bundle(order: "list[str]", bodies: "dict[str, str]") -> str:
    # The banner names the derived order on its second line, then each module under its own separator.
    parts = [
        "// Generated by scripts/_stage_website.py from js/main.js's import closure, each module after the ones it imports.\n",
        f"// Modules: {', '.join(order)}\n",
        "// Do not edit: edit the source files under js/ (SPECIFICATION.md H.2).\n",
    ]
    for name in order:
        parts.append(f"\n// ---- js/{name} ----\n")
        parts.append(bodies[name])
    return "".join(parts)


def _check_inlined(page: str, definitions: object) -> None:
    # The inlined block must parse back to the definitions: a "</script" inside it would end it early.
    start = page.index(_DEFINITIONS_OPEN) + len(_DEFINITIONS_OPEN)
    block = page[start : page.lower().find("</script", start)]
    try:
        same = json.loads(block) == definitions
    except ValueError:
        same = False
    if not same:
        raise StageError("html/index.html", "the inlined definitions do not parse back to the definitions file", "escape every '<' in the inlined JSON")


def _module(root: Path, name: str) -> "tuple[list[tuple[str, int]], str]":
    # A module's imports, each a line of the one form, and its body without them: the bundle is one module scope.
    path = f"js/{name}"
    lines = _read(root, path).split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    imports: list[tuple[str, int]] = []
    body: list[str] = []
    for number, line in enumerate(lines, 1):
        if not re.match(r"import\b", line):
            body.append(line + "\n")
        elif form := _IMPORT_LINE.fullmatch(line):
            imports.append((form.group("file"), number))
        else:
            raise StageError(f"{path}:{number}", "an import outside the one-line form", f"use the one form the bundle drops whole, a static one-line {_IMPORT_FORM} (SPECIFICATION.md H.2)")
    return imports, "".join(body)


def _page(root: Path, definitions_text: str) -> str:
    # index.html with its three exact tags replaced: the icon, the definitions before </head>, then the stylesheet.
    html = _read(root, "html/index.html")
    for tag in (_ICON_TAG, _STYLESHEET_TAG, _HEAD_END):
        if (count := html.count(tag)) != 1:
            raise StageError("html/index.html", f"has {count} of the exact tag {tag}, where the stager needs one", f"restore exactly one {tag}: the stager replaces it (SPECIFICATION.md H.7)")
    css = _read(root, "html/style.css")
    if "</style" in css.lower():
        raise StageError("html/style.css", "contains </style, which would end the inlined <style> block early", "remove it (a comment or string can say 'style end tag' instead)")
    icon = base64.b64encode(_read_bytes(root, "html/favicon.ico")).decode("ascii")
    html = html.replace(_ICON_TAG, f'<link rel="icon" href="data:image/x-icon;base64,{icon}">')
    # JSON's own escape for "<": identical once parsed, and no "</script" can end the block early.
    inlined = _DEFINITIONS_OPEN + definitions_text.replace("<", "\\u003c") + "</script>\n"
    html = html.replace(_HEAD_END, inlined + _HEAD_END)
    return html.replace(_STYLESHEET_TAG, "<style>\n" + css + "</style>")


def _read(root: Path, rel: str) -> str:
    try:
        return _read_bytes(root, rel).decode("utf-8")
    except UnicodeDecodeError as e:
        raise StageError(rel, f"is not UTF-8 ({e})", f"save {rel} as UTF-8") from None


def _read_bytes(root: Path, rel: str) -> bytes:
    try:
        return (root / rel).read_bytes()
    except FileNotFoundError:
        raise StageError(rel, "is missing", f"restore {rel}") from None
    except OSError as e:
        raise StageError(rel, f"cannot be read ({e.strerror})", f"make {rel} readable") from None


def _read_definitions(path: Path) -> tuple[str, object]:
    try:
        text = path.read_text(encoding="utf-8")
        return text, json.loads(text)
    except (OSError, UnicodeDecodeError, ValueError) as e:
        raise StageError(str(path), f"is not a readable JSON definitions file ({e})", "generate it with uv run scripts/_generate_sensortask_modules.py") from None


def _visit(root: Path, name: str, chain: "tuple[str, ...]", where: str, bodies: "dict[str, str]", order: "list[str]") -> None:
    # The depth-first post-order from the entry: a module's imports first, in source order, then itself.
    if name in chain:
        cycle = " -> ".join([*chain[chain.index(name) :], name])
        raise StageError(where, f"an import cycle: {cycle}", "move what both modules need into a module that imports neither")
    if name in order:
        return
    if chain and not (root / "js" / name).is_file():
        raise StageError(where, f"imports ./{name}, which does not exist", f"create js/{name} or import from a module that exists")
    imports, bodies[name] = _module(root, name)
    for target, line in imports:
        _visit(root, target, (*chain, name), f"js/{name}:{line}", bodies, order)
    order.append(name)


def main(argv: "list[str] | None" = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("definitions", type=Path, help="the device's generated definitions.json")
    parser.add_argument("stage_dir", type=Path, help="the directory to fill, created if absent (the caller wipes it)")
    args = parser.parse_args(argv)
    try:
        stage(REPO_ROOT, args.definitions, args.stage_dir)
    except StageError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    except OSError as e:
        print(f"error: {e.filename}: cannot be written ({e.strerror}) - fix: give the stage a writable directory", file=sys.stderr)
        return 1
    return 0


def stage(root: Path, definitions_path: Path, stage_dir: Path) -> None:
    # Everything is checked before the first write, so a refused build leaves no stage behind.
    definitions_text, definitions = _read_definitions(definitions_path)
    bodies: dict[str, str] = {}
    order: list[str] = []
    _visit(root, "main.js", (), "js/main.js", bodies, order)
    page = _page(root, definitions_text)
    _check_inlined(page, definitions)
    bundle = _bundle(order, bodies)
    (stage_dir / "js").mkdir(parents=True, exist_ok=True)
    (stage_dir / "index.html").write_text(page, encoding="utf-8")
    (stage_dir / "js" / "app.js").write_text(bundle, encoding="utf-8")


if __name__ == "__main__":
    raise SystemExit(main())
