"""The boundary protocols a typed fake stands in for, one per real class the product calls: each lists exactly the
methods src/ calls on that object (machine.I2C in asy_i2c_driver.py, machine.UART in asy_uart_driver.py, network.WLAN
in asy_wifi_service.py, the asyncio stream asy_webserver_service.py writes). For the type checker only."""

try:
    from typing import TYPE_CHECKING
except ImportError:  # typing has no runtime presence on MicroPython, on-device or in the Unix-port test build
    TYPE_CHECKING = False

if TYPE_CHECKING:
    from typing import Protocol, overload

    class I2CLike(Protocol):
        def deinit(self) -> None: ...
        def readfrom_into(self, addr: int, buf: "bytearray | memoryview", stop: bool = True, /) -> None: ...  # noqa: FBT001, FBT002 - machine.I2C's own signature
        def scan(self) -> "list[int]": ...
        def writeto(self, addr: int, buf: "bytes | bytearray | memoryview", stop: bool = True, /) -> int: ...  # noqa: FBT001, FBT002 - machine.I2C's own signature

    class UARTLike(Protocol):
        def deinit(self) -> None: ...
        def txdone(self) -> bool: ...
        def write(self, buf: "bytes | bytearray | memoryview", /) -> "int | None": ...

    class WLANLike(Protocol):
        @overload
        def active(self) -> bool: ...
        @overload
        def active(self, value: bool, /) -> object: ...  # noqa: FBT001 - network.WLAN.active()'s own signature
        def config(self, *, essid: str = ..., password: str = ..., pm: int = ...) -> object: ...
        def connect(self, ssid: "str | None" = None, key: "str | None" = None, /) -> None: ...
        def deinit(self) -> object: ...
        def disconnect(self) -> None: ...
        def ifconfig(self) -> "tuple[str, str, str, str]": ...
        def isconnected(self) -> bool: ...
        @overload
        def status(self) -> object: ...
        @overload
        def status(self, param: str, /) -> object: ...

    class WriterLike(Protocol):
        def close(self) -> None: ...
        def get_extra_info(self, name: str, /) -> object: ...
        async def aclose(self) -> None: ...
        async def awrite(self, data: bytes, /) -> None: ...
        async def wait_closed(self) -> None: ...
