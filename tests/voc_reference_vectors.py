SRAW_COUNT = 20000
# vocalgorithm_init(), then one vocalgorithm_process() per sraw_sequence() sample: the index after samples
# 0, 500, 1000, ... and CRC-32/MPEG-2 (asy_crc_checks.CRC32) over every index as two little-endian bytes.
