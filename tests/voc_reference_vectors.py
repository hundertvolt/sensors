def sraw_sequence(count: int = SRAW_COUNT) -> "Iterator[int]":
    # A walk inside 20001..52767 (LCG x = (1103515245 * x + 12345) mod 2**31, seed 20260929): a step of
    # (x >> 15) % 401 - 200 reflected at the bounds, or a jump to 20001 + 128 * (x >> 15) when x >> 15 < 256;
    # sample 500 of every 1000 is 0 and sample 999 is 65000, both outside the valid range.
    x = 20260929
    sraw = 30000
    for i in range(count):
        x = (1103515245 * x + 12345) & 0x7FFFFFFF
        if i % 1000 == 500:
            yield 0
        elif i % 1000 == 999:
            yield 65000
        else:
            r = x >> 15
            if r < 256:
                sraw = 20001 + r * 128
            else:
                sraw += r % 401 - 200
                if sraw < 20001:
                    sraw = 40002 - sraw
                elif sraw > 52767:
                    sraw = 105534 - sraw
            yield sraw
