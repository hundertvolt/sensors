def test_every_drift_from_the_bundling_rules_is_refused_naming_where_and_the_fix(tmp_path: Path, changes: "dict[str, str | None]", needles: "tuple[str, ...]") -> None:
    _refused(_site(tmp_path, changes), *needles)


def test_definitions_that_are_not_json_are_refused_naming_the_file(tmp_path: Path) -> None:
    _refused(_site(tmp_path, definitions="{not json"), "definitions.json")


def test_a_script_end_tag_in_a_label_is_escaped_and_the_inlined_block_parses_back(tmp_path: Path) -> None:
    hostile = "</script><script>alert(1)</script>"
    root = _site(tmp_path, definitions=json.dumps({**_DEFINITIONS, "label": hostile}))
    page, _ = _staged(root)

    start = page.index(_DEFINITIONS_OPEN) + len(_DEFINITIONS_OPEN)
    block = page[start : page.index("</script>", start)]
    assert "<" not in block
    assert json.loads(block)["label"] == hostile


def test_the_icon_link_carries_html_favicon_ico_as_a_data_uri(tmp_path: Path) -> None:
    page, _ = _staged(_site(tmp_path))
    match = re.search(r'<link rel="icon" href="data:image/x-icon;base64,([A-Za-z0-9+/=]+)">', page)
    assert match is not None, page
    assert base64.b64decode(match.group(1)) == _ICON.read_bytes()
    assert 'href="favicon.ico"' not in page


def test_html_favicon_ico_is_one_16_by_16_image_filling_the_file() -> None:
    data = _ICON.read_bytes()
    reserved, kind, count = struct.unpack_from("<HHH", data, 0)
    width, height, _, _, planes, bits, size, offset = struct.unpack_from("<BBBBHHII", data, 6)
    assert (reserved, kind, count) == (0, 1, 1)
    assert (width, height, planes, bits) == (16, 16, 1, 32)
    assert offset == 6 + 16
    assert offset + size == len(data)


def test_the_stager_writes_only_inside_the_stage_and_creates_it(tmp_path: Path) -> None:
    root = _site(tmp_path)
    before = {p: p.read_bytes() for p in root.rglob("*") if p.is_file()}
    result = _stage(root, "deep/er/stage")
    assert result.returncode == 0, result.stderr

    after = {p: p.read_bytes() for p in root.rglob("*") if p.is_file()}
    written = sorted(p.relative_to(root).as_posix() for p in after.keys() - before.keys())
    assert written == ["deep/er/stage/index.html", "deep/er/stage/js/app.js"]
    assert {p: after[p] for p in before} == before


def test_the_real_tree_stages_main_js_import_closure_in_dependency_order(tmp_path: Path) -> None:
    # The real site against the first derived device's generated definitions: the banner's list is the
    # closure, every module follows the ones it imports, each has its separator, and the page names the device.
    definitions = tmp_path / "definitions.json"
    definitions.write_text(json.dumps(definitions_for_toml(_REPO / "devices" / f"{DEVICE_NAMES[0]}.toml", _REPO / "src")))
    result = subprocess.run([sys.executable, str(_STAGER), str(definitions), str(tmp_path / "stage")], cwd=_REPO, capture_output=True, text=True, check=False)
    assert result.returncode == 0, result.stderr
    bundle = (tmp_path / "stage" / "js" / "app.js").read_text()
    page = (tmp_path / "stage" / "index.html").read_text()

    expected: list[str] = []
    _closure(_REPO / "js", "main.js", expected)
    modules = _banner_modules(bundle)
    assert modules == expected
    assert _SEPARATOR.findall(bundle) == modules
    for position, name in enumerate(modules):
        assert set(_ONE_LINE_IMPORT.findall((_REPO / "js" / name).read_text())) <= set(modules[:position]), name
    start = page.index(_DEFINITIONS_OPEN) + len(_DEFINITIONS_OPEN)
    assert json.loads(page[start : page.index("</script>", start)])["device"]["id"] == DEVICE_NAMES[0]
