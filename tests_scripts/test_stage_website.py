import sys
from pathlib import Path

import pytest
from _devices import DEVICE_NAMES

from buildgen.definitions import definitions_for_toml

_REPO = Path(__file__).resolve().parent.parent
_STAGER = _REPO / "scripts" / "_stage_website.py"
_ICON = _REPO / "html" / "favicon.ico"
_DEFINITIONS_OPEN = '<script type="application/json" id="inlined-definitions">'
_SEPARATOR = re.compile(r"^// ---- js/(\S+) ----$", re.MULTILINE)
_ONE_LINE_IMPORT = re.compile(r'^import \{[^}]*\} from "\./([^"]+)";$', re.MULTILINE)

_INDEX = """<!DOCTYPE html>
<html lang="en">
<head>
    <title>Fixture</title>
    <link rel="icon" href="favicon.ico">
    <link rel="stylesheet" href="style.css">
</head>
<body>
    <main id="main"></main>
    <script type="module">
        import { startApp } from "../js/app.js";

        startApp({
            mainEl: document.getElementById("main"),
            // Present only once staged: a comment with a colon is not a key.
            inlinedDefinitionsEl: document.getElementById("inlined-definitions"),
        });
    </script>
</body>
</html>
"""
_MAIN = """import { helper } from "./helper.js";

/** @typedef {import("./helper.js").Shape} Shape */

/**
 * @param {{
 *   mainEl: HTMLElement, inlinedDefinitionsEl?: HTMLElement | null,
 * }} elements
 */
export function startApp(elements) {
    return helper(elements);
}
"""
_HELPER = "export function helper(value) {\n    return value;\n}\n"
_APP = 'import { helper } from "./helper.js";\nimport { mock } from "./mock.js";\n\nexport function startApp() {\n    mock(helper);\n}\n'
_MOCK = "export function mock(callback) {\n    return callback;\n}\n"
_CSS = ":root {\n    color: black;\n}\n"
_SITE = {"html/index.html": _INDEX, "html/style.css": _CSS, "js/main.js": _MAIN, "js/helper.js": _HELPER, "js/app.js": _APP, "js/mock.js": _MOCK}
_DEFINITIONS = {"device": {"id": "fixture-device"}, "label": "Fixture"}


def _banner_modules(bundle: str) -> list[str]:
    lines = bundle.split("\n")
    assert lines[0].startswith("// Generated by scripts/_stage_website.py"), lines[0]
    assert lines[1].startswith("// Modules: "), lines[1]
    return lines[1].removeprefix("// Modules: ").split(", ")


def _closure(js_dir: Path, name: str, order: list[str]) -> None:
    # An independent oracle: the depth-first post-order over each file's one-line imports.
    if name in order:
        return
    for target in _ONE_LINE_IMPORT.findall((js_dir / name).read_text()):
        _closure(js_dir, target, order)
    order.append(name)


def _refused(root: Path, *needles: str) -> None:
    # The error contract: exit 1, what/where/fix on stderr, no traceback, and nothing written.
    result = _stage(root)
    assert result.returncode == 1, (result.returncode, result.stdout, result.stderr)
    assert "Traceback" not in result.stderr, result.stderr
    assert result.stderr.startswith("error: "), result.stderr
    assert " - fix: " in result.stderr, result.stderr
    for needle in needles:
        assert needle in result.stderr, (needle, result.stderr)
    assert not (root / "stage").exists()


def _site(root: Path, changes: "dict[str, str | None] | None" = None, definitions: str | None = None) -> Path:
    # A minimal site beside a copy of the stager, which reads the tree its own scripts/ sits in; None deletes a file.
    for rel, text in {**_SITE, **(changes or {})}.items():
        path = root / rel
        if text is None:
            path.unlink(missing_ok=True)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    (root / "scripts").mkdir(exist_ok=True)
    shutil.copy(_STAGER, root / "scripts" / _STAGER.name)
    shutil.copy(_ICON, root / "html" / "favicon.ico")
    (root / "definitions.json").write_text(json.dumps(_DEFINITIONS) if definitions is None else definitions)
    return root


def _stage(root: Path, stage: str = "stage") -> "subprocess.CompletedProcess[str]":
    return subprocess.run([sys.executable, str(root / "scripts" / _STAGER.name), "definitions.json", stage], cwd=root, capture_output=True, text=True, check=False)


def _staged(root: Path) -> tuple[str, str]:
    result = _stage(root)
    assert result.returncode == 0, result.stderr
    return (root / "stage" / "index.html").read_text(), (root / "stage" / "js" / "app.js").read_text()


def test_a_valid_site_stages_the_page_and_the_bundle_and_nothing_else(tmp_path: Path) -> None:
    root = _site(tmp_path)
    page, bundle = _staged(root)

    assert sorted(p.relative_to(root / "stage").as_posix() for p in (root / "stage").rglob("*") if p.is_file()) == ["index.html", "js/app.js"]
    assert _banner_modules(bundle) == ["helper.js", "main.js"]
    assert _SEPARATOR.findall(bundle) == ["helper.js", "main.js"]
    assert "\n// ---- js/helper.js ----\nexport function helper(value) {\n" in bundle
    assert not [line for line in bundle.split("\n") if line.startswith("import ")]
    assert "function mock" not in bundle  # the prototype-only closure is never bundled
    assert '<link rel="stylesheet"' not in page
    assert "<style>\n" + _CSS + "</style>" in page


def test_import_text_in_comments_strings_templates_and_regexes_is_not_an_import(tmp_path: Path) -> None:
    # Guard: the real modules carry JSDoc `import("./x.js")` type references; none of these is code.
    helper = _HELPER + 'const NOTE = "import(\\"./mock.js\\")";\nconst PATTERN = /["\'/]import\\(/;\nconst SHOWN = `${NOTE}/import("./mock.js")`;\n'
    root = _site(tmp_path, {"js/helper.js": helper})
    _, bundle = _staged(root)
    assert "const PATTERN" in bundle


